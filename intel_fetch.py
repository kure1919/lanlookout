#!/usr/bin/env python3
"""Fetch threat-intel domain feeds and build the lanlookout intel list.

Reads `intel_sources` (URLs) and the output path (`intel.path`) from
the same lanlookout config.json as dns_watch. Each feed may contain
bare domains, full URLs (the host is extracted), hosts-file lines
("0.0.0.0 domain"), or CSV rows whose first field is a domain or URL.
Comments (#, //, ;) and blank lines are skipped; IP literals are
dropped (this list is matched against DNS names only).

Safety gates, so a broken or hijacked feed cannot wipe or poison the
list: a source yielding fewer than MIN_PER_SOURCE domains counts as
failed; if every source fails, or the merged total falls outside
[MIN_TOTAL, MAX_TOTAL], the existing list file is left untouched and
the script exits non-zero. On success the merged, de-duplicated list
is written atomically (temp file + rename) with a provenance header.

Usage: intel_fetch.py [--dry-run]
"""

import importlib.util
import ipaddress
import json
import os
import re
import sys
import time
import urllib.request
from urllib.parse import urlparse

_HERE = os.path.dirname(os.path.abspath(__file__))
_spec = importlib.util.spec_from_file_location(
    "dns_watch", os.path.join(_HERE, "dns_watch.py"))
dw = importlib.util.module_from_spec(_spec)
_spec.loader.exec_module(dw)

MIN_PER_SOURCE = 10
MIN_TOTAL = 100
MAX_TOTAL = 2_000_000
_DOMAIN_RE = re.compile(r"^(?=.{4,253}$)([a-z0-9_*-]+\.)+[a-z0-9-]{2,}$")


def _clean_host(raw):
    """1トークンをドメインとして正規化する。駄目なら None。"""
    h = (raw or "").strip().strip(",;\"'").lower()
    if not h:
        return None
    if "://" in h:
        h = urlparse(h).hostname or ""
    h = h.split(":")[0].rstrip(".")
    if h.startswith("*."):
        h = h[2:]
    if not h or "." not in h or " " in h:
        return None
    try:
        ipaddress.ip_address(h)
        return None  # IP リテラルは DNS 名の突合対象ではない
    except ValueError:
        pass
    return h if _DOMAIN_RE.match(h) else None


def parse_feed(text):
    """フィード本文からドメイン集合を取り出す。"""
    out = set()
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith(("#", "//", ";", "!")):
            continue
        token = None
        if "://" in line:
            token = line.split()[0]
        else:
            parts = line.replace(",", " ").split()
            if len(parts) >= 2 and _is_ip(parts[0]):
                token = parts[1]       # hosts 形式: 0.0.0.0 domain
            elif parts:
                token = parts[0]       # 素のドメイン or CSV 先頭列
        d = _clean_host(token)
        if d:
            out.add(d)
    return out


def _is_ip(s):
    try:
        ipaddress.ip_address(s)
        return True
    except ValueError:
        return False


def fetch(url, timeout=60):
    req = urllib.request.Request(
        url, headers={"User-Agent": "lanlookout-intel-fetch/1.0"})
    with urllib.request.urlopen(req, timeout=timeout) as r:
        return r.read().decode("utf-8", errors="replace")


def build(sources, fetcher=fetch):
    """(merged_domains, [(url, count_or_None)]) を返す。"""
    merged = set()
    report = []
    for url in sources:
        try:
            domains = parse_feed(fetcher(url))
        except Exception as e:
            print("intel_fetch: %s failed: %s" % (url, e), file=sys.stderr)
            domains = set()
        if len(domains) < MIN_PER_SOURCE:
            print("intel_fetch: %s yielded only %d domains; treated as "
                  "failed" % (url, len(domains)), file=sys.stderr)
            report.append((url, None))
            continue
        merged |= domains
        report.append((url, len(domains)))
    return merged, report


def main(argv):
    dry_run = "--dry-run" in argv
    cfg = dw.CONFIG
    sources = cfg["intel_sources"]
    out_path = cfg["intel"]["path"]
    merged, report = build(sources)
    ok_sources = [r for r in report if r[1] is not None]
    if not ok_sources:
        print("intel_fetch: all sources failed; keeping existing list",
              file=sys.stderr)
        return 2
    if not (MIN_TOTAL <= len(merged) <= MAX_TOTAL):
        print("intel_fetch: merged total %d outside [%d, %d]; keeping "
              "existing list" % (len(merged), MIN_TOTAL, MAX_TOTAL),
              file=sys.stderr)
        return 2
    stamp = time.strftime("%Y-%m-%dT%H:%M:%S%z")
    header = ["# lanlookout intel domains (generated by intel_fetch.py)",
              "# generated: %s" % stamp]
    for url, n in report:
        header.append("# source: %s -> %s"
                      % (url, ("%d domains" % n) if n is not None
                         else "FAILED (skipped)"))
    header.append("# total: %d" % len(merged))
    body = "\n".join(header + sorted(merged)) + "\n"
    if dry_run:
        print("intel_fetch dry-run: %d domains from %d/%d sources; "
              "not writing %s" % (len(merged), len(ok_sources),
                                  len(report), out_path))
        return 0
    os.makedirs(os.path.dirname(out_path), exist_ok=True)
    tmp = out_path + ".tmp"
    with open(tmp, "w", encoding="utf-8") as f:
        f.write(body)
    os.replace(tmp, out_path)
    print("intel_fetch: wrote %d domains to %s" % (len(merged), out_path))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
